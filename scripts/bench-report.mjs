// Builds docs/benchmarks.{json,md} from the per-strategy Gatling summaries written by bench-strategies.sh
import fs from 'node:fs';
import path from 'node:path';

const [work, out, users, amount, limit] = process.argv.slice(2);
const order = ['naive', 'db-pessimistic', 'db-optimistic', 'redis-lock', 'redis-lua', 'db-pessimistic-platform-threads'];
const rows = [];
for (const label of order) {
  const resFile = path.join(work, `${label}.json`);
  const metaFile = path.join(work, `${label}.meta.json`);
  if (!fs.existsSync(resFile) || !fs.existsSync(metaFile)) continue;
  const res = JSON.parse(fs.readFileSync(resFile, 'utf8'));
  const meta = JSON.parse(fs.readFileSync(metaFile, 'utf8'));
  rows.push({
    strategy: label.replace('-platform-threads', ' (platform threads)'),
    users: res.users,
    approved_count: res.approved_count,
    declined_count: res.declined_count,
    overspend_amount: res.overspend_amount,
    p50_ms: res.p50_ms,
    p95_ms: res.p95_ms,
    p99_ms: res.p99_ms,
    throughput_rps: res.throughput_rps,
    failed_requests: res.users - res.completed,
  });
}
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'benchmarks.json'), JSON.stringify(rows, null, 2));

const head = '| strategy | approved | declined | overspend ¥ | p50 ms | p95 ms | p99 ms | req/s | failed |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|\n';
const body = rows.map(r => `| ${r.strategy} | ${r.approved_count} | ${r.declined_count} | ${r.overspend_amount} | ${r.p50_ms} | ${r.p95_ms} | ${r.p99_ms} | ${r.throughput_rps} | ${r.failed_requests} |`).join('\n');
const md = `# Benchmarks

Generated by \`scripts/bench-strategies.sh\` on ${new Date().toISOString().slice(0, 10)}.

**Scenario:** ${users} concurrent authorisations of ¥${amount} against one card with a ¥${limit} limit (so exactly ${limit / amount} may be approved).
All requests go through nginx to 2 auth-service instances (round-robin) backed by Postgres 17, Redis 7, Kafka and DynamoDB Local.
Latencies are client-side (Gatling) in milliseconds. \`overspend\` = approved × amount − limit.

${head}${body}

## Reading the table

- \`naive\` is read-then-write with no lock: concurrent requests read the same balance, so it approves far more than the limit allows (the overspend column). See [INC-001](incidents/INC-001-overspend-naive.md).
- \`db-pessimistic\`, \`db-optimistic\`, \`redis-lock\` and \`redis-lua\` all approve exactly ${limit / amount} and overspend ¥0.
- \`redis-lua\` does the check-and-hold in one atomic script in Redis, so it never queues on a row lock or retries.

## Virtual threads

The \`db-pessimistic (platform threads)\` row is the same scenario with \`spring.threads.virtual.enabled=false\`
(Tomcat's 200 platform worker threads, each blocking on the DB connection pool or the row lock).
With virtual threads on, the 1,000 in-flight requests park cheaply instead of being queued behind 200 threads.
Compare it with the \`db-pessimistic\` row above.
`;
fs.writeFileSync(path.join(out, 'benchmarks.md'), md);
console.log(md);
