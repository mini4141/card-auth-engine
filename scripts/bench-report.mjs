// Builds docs/benchmarks.{json,md} from the per-strategy Gatling summaries written by bench-strategies.sh
import fs from 'node:fs';
import path from 'node:path';

const [work, out, users, amount, limit] = process.argv.slice(2);
const steadyRate = process.env.STEADY_RATE || 100;
const steadySeconds = process.env.STEADY_SECONDS || 20;
const base = ['naive', 'db-pessimistic', 'db-optimistic', 'redis-lock', 'redis-lua'];
const order = [...base, 'db-pessimistic-platform-threads', ...base.map(s => `steady-${s}`)];

const rows = [];
for (const label of order) {
  const resFile = path.join(work, `${label}.json`);
  if (!fs.existsSync(resFile)) continue;
  const res = JSON.parse(fs.readFileSync(resFile, 'utf8'));
  rows.push({
    mode: res.mode || 'burst',
    strategy: label.replace('steady-', '').replace('-platform-threads', ' (platform threads)'),
    users: res.users,
    approved_count: res.approved_count,
    declined_count: res.declined_count,
    overspend_amount: res.overspend_amount,
    p50_ms: res.p50_ms,
    p95_ms: res.p95_ms,
    p99_ms: res.p99_ms,
    throughput_rps: res.throughput_rps,
    failed_requests: res.users - res.completed,
  });
}
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'benchmarks.json'), JSON.stringify(rows, null, 2));

const head = '| strategy | approved | declined | overspend ¥ | p50 ms | p95 ms | p99 ms | req/s | failed |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|\n';
const line = r => `| ${r.strategy} | ${r.approved_count} | ${r.declined_count} | ${r.overspend_amount} | ${r.p50_ms} | ${r.p95_ms} | ${r.p99_ms} | ${r.throughput_rps} | ${r.failed_requests} |`;
const burst = rows.filter(r => r.mode === 'burst');
const steady = rows.filter(r => r.mode === 'steady');

const md = `# Benchmarks

Generated by \`scripts/bench-strategies.sh\` on ${new Date().toISOString().slice(0, 10)}.
Raw Gatling reports: \`proof/phase1-local/tests/gatling-*\`.

**Stack:** nginx round-robin to 2 auth-service instances, Postgres 17, Redis 7, Kafka (KRaft), DynamoDB Local, all in Docker Desktop (WSL2) on a Windows laptop, with the Gatling JVM on the same machine.
Absolute numbers are therefore bounded by that environment (about 300 req/s through the Docker network even for \`/actuator/health\`); the *differences between strategies* are what matter.
Latencies are client-side (Gatling), in milliseconds.

## Burst: ${users} concurrent authorisations of ¥${amount} on one ¥${limit} card

Exactly ${limit / amount} may be approved. \`overspend\` = approved × amount − limit. Users are injected over 3 s (Docker Desktop refuses part of a 1,000-connection SYN burst), so ~all ${users} requests are in flight together.

${head}${burst.map(line).join('\n')}

- \`naive\` (read-then-write, no lock) approves far more than the limit allows. See [INC-001](incidents/INC-001-overspend-naive.md).
- \`db-pessimistic\`, \`db-optimistic\`, \`redis-lock\` and \`redis-lua\` approve exactly ${limit / amount} and overspend ¥0.
- \`redis-lua\` does check-and-hold in one atomic script, so it never queues on a row lock, a distributed lock or version-conflict retries, and it has the lowest latency of the safe strategies.

## Steady load: ${steadyRate} authorisations/s for ${steadySeconds}s (what a normal card sees)

One card with an effectively unlimited limit (amount ¥10), so every request is approved and the cost of the strategy itself shows.

${head}${steady.map(line).join('\n')}

## Virtual threads (db-pessimistic, burst)

${(() => {
  const on = burst.find(r => r.strategy === 'db-pessimistic');
  const off = burst.find(r => r.strategy === 'db-pessimistic (platform threads)');
  if (!on || !off) return '_not run_';
  return `| threads | p50 ms | p95 ms | p99 ms | req/s |\n|---|---:|---:|---:|---:|\n| virtual (\`spring.threads.virtual.enabled=true\`) | ${on.p50_ms} | ${on.p95_ms} | ${on.p99_ms} | ${on.throughput_rps} |\n| platform (Tomcat 200 worker threads) | ${off.p50_ms} | ${off.p95_ms} | ${off.p99_ms} | ${off.throughput_rps} |\n\nWith platform threads, at most 200 requests are in flight inside Tomcat; each blocks on the Hikari pool or the row lock, so the rest queue at the connector. Virtual threads park cheaply while waiting, so all ${users} requests can be in flight. Here the DB row lock and a 20-connection pool are the real limit, so the gain is modest; the benefit shows on strategies that wait on I/O instead of a lock.`;
})()}
`;
fs.writeFileSync(path.join(out, 'benchmarks.md'), md);
console.log(md);
